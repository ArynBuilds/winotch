// Writes src/core/logos.ts: each app's logo as SVG path data, drawn in the
// island's one colour. Brand marks come from Simple Icons (CC0), pinned to one
// release so the output never changes under us; the Tentis mark is our own.
//
//   node scripts/gen-logos.mjs           writes src/core/logos.ts
//   node scripts/gen-logos.mjs --check   fails if it is out of date

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const SIMPLE_ICONS = "13.21.0";
const OUTPUT = join(dirname(fileURLToPath(import.meta.url)), "..", "src", "core", "logos.ts");

/** Simple Icons slugs winotch shows. */
const BRANDS = ["github", "stripe", "notion", "spotify", "gmail", "claude"];

/** Our own marks, path data in the same 24 × 24 box. */
const OWN = {
  // gtm.js is a Tentis tool, so it carries the Tentis mark.
  // Today: a calendar page with a check on it, drawn for winotch.
  today: "M5 4H19A3 3 0 0 1 22 7V19A3 3 0 0 1 19 22H5A3 3 0 0 1 2 19V7A3 3 0 0 1 5 4ZM4 9.5V19A1 1 0 0 0 5 20H19A1 1 0 0 0 20 19V9.5ZM7.5 1.5A1 1 0 0 1 8.5 2.5V5.5A1 1 0 0 1 6.5 5.5V2.5A1 1 0 0 1 7.5 1.5ZM16.5 1.5A1 1 0 0 1 17.5 2.5V5.5A1 1 0 0 1 15.5 5.5V2.5A1 1 0 0 1 16.5 1.5ZM8.21 13.29L10.5 15.59L15.79 10.29L17.21 11.71L10.5 18.41L6.79 14.71Z",
  tentis: "M6.673 3.000H17.327A3.673 3.673 0 0 1 17.327 10.347H6.673A3.673 3.673 0 0 1 6.673 3.000ZM3.000 17.327a3.673 3.673 0 1 0 7.347 0a3.673 3.673 0 1 0 -7.347 0ZM13.653 17.327a3.673 3.673 0 1 0 7.347 0a3.673 3.673 0 1 0 -7.347 0Z",
};

/**
 * Logo ids → the mark they carry. The app registry names each app's logo id
 * (src-tauri/src/apps.rs: a built-in's `logo`, an API app's own id); Claude
 * Code's pill is "claude".
 */
const USES = {
  claude: "claude",
  github: "github",
  stripe: "stripe",
  notion: "notion",
  spotify: "spotify",
  gmail: "gmail",
  gtm: "tentis",
  today: "today",
};

async function brandPath(slug) {
  const url = `https://cdn.jsdelivr.net/npm/simple-icons@${SIMPLE_ICONS}/icons/${slug}.svg`;
  const res = await fetch(url);
  if (!res.ok) throw new Error(`${slug}: ${res.status} from ${url}`);
  const d = /<path d="([^"]+)"/.exec(await res.text())?.[1];
  if (!d) throw new Error(`${slug}: no path in ${url}`);
  return d;
}

const paths = { ...Object.fromEntries(await Promise.all(BRANDS.map(async (s) => [s, await brandPath(s)]))), ...OWN };
for (const [id, mark] of Object.entries(USES)) {
  if (!paths[mark]) throw new Error(`${id} uses "${mark}", which is neither a brand nor our own`);
}

const out = `// Each app's own logo, drawn in the island's one colour. The brand marks are
// from Simple Icons (simple-icons@${SIMPLE_ICONS}, CC0): path data in a 24 x 24 box.
// They identify the services winotch connects to; the trademarks are their
// owners'. gtm.js is a Tentis tool, so it carries the Tentis mark; Today's
// calendar is our own.
// Generated by scripts/gen-logos.mjs: do not edit by hand.

const PATHS = {
${Object.entries(paths).map(([k, d]) => `  ${k}: ${JSON.stringify(d)},`).join("\n")}
} as const;

/** A logo id (the registry's \`logo\`) → its mark. */
export const LOGOS: Record<string, string> = {
${Object.entries(USES).map(([id, mark]) => `  ${id}: PATHS.${mark},`).join("\n")}
};
`;

if (process.argv.includes("--check")) {
  if (readFileSync(OUTPUT, "utf8").replace(/\r\n/g, "\n") !== out) {
    console.error("src/core/logos.ts is out of date: run `node scripts/gen-logos.mjs`.");
    process.exit(1);
  }
  console.log("src/core/logos.ts is up to date.");
} else {
  writeFileSync(OUTPUT, out);
  console.log(`Wrote ${Object.keys(USES).length} logos to src/core/logos.ts`);
}
