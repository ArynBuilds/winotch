    #[test]
    fn the_apps_switches_of_an_older_file_load_once_and_are_not_written_again() {
        // They moved to the app registry (apps.rs migrate reads them at start).
        let mut object = custom().as_object().unwrap().clone();
        object.insert("activeIntegrations".into(), json!(["integration_notion", "integration_spotify"]));
        object.insert("quietApps".into(), json!(["integration_stripe"]));
        let loaded = parse(&serde_json::to_vec(&object).unwrap()).unwrap();
        assert_eq!(loaded.active_integrations, ["integration_notion", "integration_spotify"]);
        assert_eq!(loaded.quiet_apps, ["integration_stripe"]);
        assert_eq!(shown(&loaded), custom(), "everything else as it was");
        // The wrong type costs only them.
        object.insert("activeIntegrations".into(), json!("integration_github"));
        let salvaged = parse(&serde_json::to_vec(&object).unwrap()).unwrap();
        assert_eq!(salvaged.active_integrations, Settings::default().active_integrations);
        assert_eq!(salvaged.quiet_apps, ["integration_stripe"]);
        assert_eq!(shown(&salvaged), custom());
        // Saved again, they are gone from the file.
        let (dir, file) = scratch("deprecated-apps");
        save_to(&file, &loaded).unwrap();
        let written: Value = serde_json::from_slice(&std::fs::read(&file).unwrap()).unwrap();
        assert!(written.get("activeIntegrations").is_none() && written.get("quietApps").is_none());
        // A file without them reads as before the registry's defaults: GitHub on.
        assert_eq!(load_from(&file).active_integrations, ["integration_github"]);
        let _ = std::fs::remove_dir_all(&dir);
    }

