// Preferences, stored as plain JSON in settings.json under platform::config_dir().
// No secret ever lands here — API keys live in the OS keychain (see secrets.rs).

use serde::{Deserialize, Serialize};
use serde_json::{Map, Value};
use std::io::ErrorKind;
use std::path::{Path, PathBuf};
use std::sync::{Mutex, MutexGuard, PoisonError};

/// A field the file lacks takes its value from `Default`, so a settings.json
/// written by an older build still loads, whatever has been added since.
#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(rename_all = "camelCase", default)]
pub struct Settings {
    pub sound_enabled: bool,
    pub sound_volume: f64,
    pub auto_close_interval: f64,
    /// Hovering the island opens it all the way, and it folds again shortly
    /// after the pointer leaves (the Mac's "Open on hover"). Off by default.
    pub open_on_hover: bool,
    /// Deprecated: the built-in apps that were on the island
    /// ("integration_github"…). Their switches live in the app registry now
    /// (apps.rs, apps.json); a file from before is read once to move them
    /// there (apps::migrate), and the next save leaves this out.
    #[serde(skip_serializing)]
    pub active_integrations: Vec<String>,
    /// Deprecated: the built-ins that could not open the island, moved like
    /// `active_integrations` (into each app's `muted`).
    #[serde(skip_serializing)]
    pub quiet_apps: Vec<String>,
    /// "primary" = the main display, "cursor" = whichever display the mouse is on.
    pub screen: String,
    pub autostart: bool,
    pub hooks_installed: bool,
    /// Claude model of the calls made on the user's key (the notes of a call,
    /// « OK Tent »). Changeable in the settings window.
    pub model: String,
    /// Show the Claude plan pill (5 h and weekly limits) in the island's header.
    /// Off until the user turns it on, so the header stays as it shipped.
    pub show_plan_in_notch: bool,
    /// winotch's status line relay is the one in Claude Code's settings.json.
    /// Like `hooks_installed`, the real state wins at launch over what was stored.
    pub plan_relay_installed: bool,
    /// The Claude Code session the island's chat talks to: a session id, or
    /// "new:<folder>" to start one there (src/core/claude-sessions.ts). Empty
    /// until one is picked in the chat view.
    pub chat_session: String,
    /// The model the chat runs Claude Code with: an alias `claude --model`
    /// takes ("opus", "sonnet", "fable"), or "" for Claude Code's own default.
    pub chat_model: String,
    /// The chat's effort level ("low" … "max"), or "" for Claude Code's default.
    pub chat_effort: String,
    /// winotch: what the console shows of a conversation: "recent" (its latest
    /// exchange) or "all".
    pub chat_history: String,
    /// winotch: how fast an answer asked for by voice is read along, in words a
    /// minute (src/views/say.ts PACES).
    pub say_pace: u32,
    /// Global shortcuts the user changed, by action id; the others keep their
    /// default (see shortcuts.rs).
    pub shortcuts: crate::shortcuts::Bindings,
    /// Interface language: "" follows the system, else one of i18n::LANGUAGES
    /// ("fr", "pt-BR", "zh-Hans"…). Kept as it comes: a code this build
    /// doesn't know reads as "".
    pub language: String,
    /// The Gmail accounts (mail/). Their app passwords are in the credential
    /// store, never here. Only the mail_* commands change this list: a page
    /// saving its copy of the settings keeps what Rust has (lib.rs save_settings).
    pub gmail_accounts: Vec<GmailAccount>,
    /// How winotch signs in to GitHub (github_auth.rs): "cli" (the GitHub
    /// CLI's login, `gh auth token`), "token" (the one in the credential
    /// store), or "" (never chosen: the CLI when it is signed in, else the
    /// token). A file from before it reads as "".
    pub github_auth: String,
    /// The Get started page has been shown (once, at the first start). A
    /// settings.json from before it means winotch ran already: true then.
    pub welcomed: bool,
}

#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
